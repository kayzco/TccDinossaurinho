<?php

function icone($nome, $classe = "icone") {
    static $mapas = [
        "play"   => ["..........", "..##......", "..####....", "..######..", "..#######.", "..#######.", "..######..", "..####....", "..##......", ".........."],
        "user"   => ["...####...", "..######..", "..######..", "..######..", "...####...", "..........", ".########.", "##########", "##########", "##########"],
        "lock"   => ["..######..", ".##....##.", ".#......#.", "##########", "##########", "####..####", "####..####", "#####.####", "##########", "##########"],
        "gear"   => ["....##....", "..#.##.#..", "..######..", "#.##..##.#", "####..####", "####..####", "#.##..##.#", "..######..", "..#.##.#..", "....##...."],
        "exit"   => ["#####.....", "#...#..#..", "#...#...#.", "#...######", "#...######", "#...#...#.", "#...#..#..", "#####.....", "..........", ".........."],
        "trophy" => ["##########", "#.######.#", "#.######.#", ".########.", "..######..", "...####...", "....##....", "....##....", "...####...", "..######.."],
        "home"   => ["....##....", "...####...", "..######..", ".########.", "##########", ".##....##.", ".##.##.##.", ".##.##.##.", ".##.##.##.", ".########."],
        "voltar" => ["..........", "...#......", "..##......", ".#########", "##########", ".#########", "..##......", "...#......", "..........", ".........."],
        "pause"  => ["..........", ".###..###.", ".###..###.", ".###..###.", ".###..###.", ".###..###.", ".###..###.", ".###..###.", ".###..###.", ".........."],
        "coroa"  => ["#...##...#", "##.####.##", "##########", "##########", ".########.", ".########."],
        "mail"   => ["..........", "##########", "###....###", "#.##..##.#", "#..####..#", "#...##...#", "#........#", "##########", "..........", ".........."],
    ];
    $linhas = $mapas[$nome] ?? [];
    $alt = count($linhas);
    $rects = "";
    foreach ($linhas as $y => $linha) {
        preg_match_all('/#+/', $linha, $m, PREG_OFFSET_CAPTURE);
        foreach ($m[0] as [$trecho, $x]) {
            $rects .= '<rect x="' . $x . '" y="' . $y . '" width="' . strlen($trecho) . '" height="1"/>';
        }
    }
    return '<svg class="' . $classe . '" viewBox="0 0 10 ' . $alt . '" aria-hidden="true" shape-rendering="crispEdges" fill="currentColor">' . $rects . '</svg>';
}